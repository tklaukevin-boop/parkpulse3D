// Compute Entrance Queue Jam Risk & Wait Time (車場門口排隊避坑警戒演算法)
export function evaluateCarparkQueueRisk(
  availableSpaces: number,
  adjacentRoadSpeedKmh: number
): { queueRisk: boolean; estimatedWaitMins: number } {
  const queueRisk = availableSpaces < 5 && adjacentRoadSpeedKmh < 20;
  if (!queueRisk) {
    return {
      queueRisk: false,
      estimatedWaitMins: availableSpaces < 8 ? 5 : 0,
    };
  }
  const deficitFactor = Math.max(1, 5 - availableSpaces);
  const speedPenalty = Math.max(1, Math.round((20 - adjacentRoadSpeedKmh) * 1.4));
  return {
    queueRisk: true,
    estimatedWaitMins: Math.min(35, 10 + deficitFactor * 3 + speedPenalty),
  };
}

export function matchesEvPowerFilter(
  cp: CarparkFacility,
  evPowerFilter: EvPowerFilter
): boolean {
  if (evPowerFilter === 'all') return true;
  if (evPowerFilter === 'dc_super') {
    // Flagship Ultra-Fast DC Supercharging Hubs (>= 60kW DC fast bays with available DC gun)
    return (
      cp.evInfo.hasEv &&
      cp.evInfo.dcMaxKw >= 60 &&
      cp.evInfo.dcFastCount >= 2 &&
      cp.evInfo.dcAvailable > 0
    );
  }
  if (evPowerFilter === 'ac_medium') {
    // Dedicated AC Medium Type-2 Charging Hubs (7-22kW AC hubs with available AC bays)
    return (
      cp.evInfo.hasEv &&
      cp.evInfo.acCount > 0 &&
      cp.evInfo.acAvailable > 0
    );
  }
  return true;
}

