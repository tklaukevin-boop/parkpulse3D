export function buildInitialSmartMeters(): SmartMeterSpot[] {
  const spots: SmartMeterSpot[] = [];

  // Combine core street corridors with territory-wide neighborhood corridors
  const allCorridors: StreetMeterTemplate[] = [
    ...STREET_METER_CORRIDORS,
    ...HK_TERRITORY_NEIGHBORHOOD_SEEDS.map((seed, idx) => ({
      prefix: `HK-G${String(idx + 1).padStart(2, '0')}`,
      streetZh: seed.streetZh,
      streetSc: seed.streetSc,
      streetEn: seed.streetEn,
      districtKey: seed.districtKey,
      districtZh: seed.districtZh,
      districtSc: seed.districtSc,
      districtEn: seed.districtEn,
      start: [seed.coordinates[0] - 0.0018, seed.coordinates[1] - 0.0012] as [number, number],
      end: [seed.coordinates[0] + 0.0018, seed.coordinates[1] + 0.0012] as [number, number],
      count: 14,
      maxDurationMins: (idx % 2 === 0 ? 60 : 120) as 15 | 30 | 60 | 120,
      occupancyRate: 0.48,
    })),
  ];

  allCorridors.forEach((corridor, cIdx) => {
    for (let i = 0; i < corridor.count; i++) {
      const t = corridor.count > 1 ? i / (corridor.count - 1) : 0;
      const lng = corridor.start[0] + (corridor.end[0] - corridor.start[0]) * t;
      const lat = corridor.start[1] + (corridor.end[1] - corridor.start[1]) * t;
      const hash = ((cIdx + 1) * 31 + i * 17) % 100;
      const occupied = hash < corridor.occupancyRate * 100;
      const baySuffix = i % 2 === 0 ? 'A' : 'B';
      const poleNum = String(101 + Math.floor(i / 2));

      spots.push({
        id: `${corridor.prefix}-${poleNum}${baySuffix}`,
        meterPoleId: `${corridor.prefix}-${poleNum}`,
        streetZh: corridor.streetZh,
        streetSc: corridor.streetSc,
        streetEn: corridor.streetEn,
        districtKey: corridor.districtKey,
        districtZh: corridor.districtZh,
        districtSc: corridor.districtSc,
        districtEn: corridor.districtEn,
        coordinates: [Number(lng.toFixed(6)), Number(lat.toFixed(6))],
        occupied,
        maxDurationMins: corridor.maxDurationMins,
        ratePer15MinHk: 4.0,
        operatingHours: '08:00 - 20:00',
        vehicleTypeZh: i % 7 === 0 ? '輕型貨車 / 私家車' : '私家車專用錶位',
        vehicleTypeSc: i % 7 === 0 ? '轻型货车 / 私家车' : '私家车专用表位',
        vehicleTypeEn: i % 7 === 0 ? 'LGV / Private Car' : 'Private Car Only',
        lastSensorPingSecs: 3 + ((i * 7) % 24),
      });
    }
  });
  return spots;
}

// Spatial Bounding-Box Check with Padding (in degrees) for 60 FPS Viewport Culling
export function isPointInBBox(
  coords: [number, number],
  bbox: ViewportBBox | null,
  paddingDeg: number = 0.015
): boolean {
  if (!bbox) return true;
  const [west, south, east, north] = bbox;
  const [lng, lat] = coords;
  return (
    lng >= west - paddingDeg &&
    lng <= east + paddingDeg &&
    lat >= south - paddingDeg &&
    lat <= north + paddingDeg
  );
}

// Detect Nearest HK District / Neighborhood Name from Map Viewport Center
export function detectViewportRegionLabel(
  center: [number, number],
  locale: LocaleKey
): string {
  let bestDist = Infinity;
  let bestZh = '維港核心區';
  let bestSc = '维港核心区';
  let bestEn = 'Victoria Harbour';

  for (const preset of DISTRICT_PRESETS) {
    if (preset.key === 'all') continue;
    const d = calculateDistanceKm(center, preset.center);
    if (d < bestDist) {
      bestDist = d;
      bestZh = preset.labelZh;
      bestSc = preset.labelSc;
      bestEn = preset.labelEn;
    }
  }

  for (const seed of HK_TERRITORY_NEIGHBORHOOD_SEEDS) {
    const d = calculateDistanceKm(center, seed.coordinates);
    if (d < bestDist) {
      bestDist = d;
      bestZh = seed.districtZh;
      bestSc = seed.districtSc;
      bestEn = seed.districtEn;
    }
  }

  return pickLocaleText(locale, bestZh, bestSc, bestEn);
}

// Detect the nearest DistrictKey from any [lng, lat] coordinate
export function detectNearestDistrictKey(center: [number, number]): Exclude<DistrictKey, 'all'> {
  let bestDist = Infinity;
  let bestKey: Exclude<DistrictKey, 'all'> = 'central';

  for (const preset of DISTRICT_PRESETS) {
    if (preset.key === 'all') continue;
    const d = calculateDistanceKm(center, preset.center);
    if (d < bestDist) {
      bestDist = d;
      bestKey = preset.key as Exclude<DistrictKey, 'all'>;
    }
  }
  return bestKey;
}

// Create an octagon 3D footprint polygon around a [lng, lat] point for MapLibre fill-extrusion 3D Energy Pillars
export function createOctagonPolygon(
  center: [number, number],
  radiusMeters: number = 24
): [number, number][] {
  const [lng, lat] = center;
  const latDegPerMeter = 1 / 111320;
  const lngDegPerMeter = 1 / (111320 * Math.cos((lat * Math.PI) / 180));
  const coords: [number, number][] = [];
  const sides = 8;

  for (let i = 0; i <= sides; i++) {
    const angle = (i * 2 * Math.PI) / sides;
    const dx = Math.cos(angle) * radiusMeters * lngDegPerMeter;
    const dy = Math.sin(angle) * radiusMeters * latDegPerMeter;
    coords.push([Number((lng + dx).toFixed(6)), Number((lat + dy).toFixed(6))]);
  }
  return coords;
}

// Haversine distance in kilometers
export function calculateDistanceKm(
  coord1: [number, number],
  coord2: [number, number]
): number {
  const toRad = (deg: number) => (deg * Math.PI) / 180;
  const R = 6371;
  const dLat = toRad(coord2[1] - coord1[1]);
  const dLng = toRad(coord2[0] - coord1[0]);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(toRad(coord1[1])) *
      Math.cos(toRad(coord2[1])) *
      Math.sin(dLng / 2) *
      Math.sin(dLng / 2);
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

// Simulate live telemetry fluctuation across Carparks, Smart Meters, Roads, and Tunnels
export function simulateTelemetryTick(
  carparks: CarparkFacility[],
  meters: SmartMeterSpot[],
  roads: RoadSegment[],
  tunnels: TunnelCrossingMonitor[] = INITIAL_TUNNEL_MONITORS
): {
  carparks: CarparkFacility[];
  meters: SmartMeterSpot[];
  roads: RoadSegment[];
  tunnels: TunnelCrossingMonitor[];
} {
  const nowStr = new Date().toLocaleTimeString('zh-HK', { hour12: false });

  // 1. Fluctuate road speeds slightly
  const nextRoads: RoadSegment[] = roads.map((road) => {
    const delta = Math.floor(Math.random() * 7) - 3; // -3 to +3 km/h
    const nextSpeed = Math.max(8, Math.min(road.speedLimitKmh, road.speedKmh + delta));
    const status: RoadSegment['status'] =
      nextSpeed > 40 ? 'good' : nextSpeed >= 20 ? 'average' : 'bad';
    return {
      ...road,
      speedKmh: nextSpeed,
      status,
    };
  });

  const roadSpeedMap = new Map<string, number>();
  nextRoads.forEach((r) => roadSpeedMap.set(r.id, r.speedKmh));

  // 2. Fluctuate carpark vacancies & recompute "Entrance Queue Jam" Warning Algorithm
  const nextCarparks: CarparkFacility[] = carparks.map((cp) => {
    const delta = Math.floor(Math.random() * 5) - 2; // -2 to +2 spaces
    const nextAvail = Math.max(0, Math.min(cp.totalSpaces, cp.availableSpaces + delta));
    const adjSpeed =
      (cp.adjacentRoadId ? roadSpeedMap.get(cp.adjacentRoadId) : undefined) ??
      cp.adjacentRoadSpeedKmh ??
      40;

    let nextEvInfo = cp.evInfo;
    if (cp.evInfo) {
      const dcDelta = Math.random() > 0.7 ? (Math.random() > 0.5 ? 1 : -1) : 0;
      const nextDcAvail = Math.max(
        0,
        Math.min(cp.evInfo.dcFastCount, (cp.evInfo.dcAvailable ?? 0) + dcDelta)
      );
      nextEvInfo = {
        ...cp.evInfo,
        dcAvailable: nextDcAvail,
      };
    }

    const { queueRisk, estimatedWaitMins } = evaluateCarparkQueueRisk(nextAvail, adjSpeed);

    return {
      ...cp,
      availableSpaces: nextAvail,
      adjacentRoadSpeedKmh: adjSpeed,
      queueRisk,
      estimatedWaitMins,
      evInfo: nextEvInfo,
      lastUpdated: nowStr,
    };
  });

  // 3. Flip ~5% of curbside smart meters sensor states
  const nextMeters: SmartMeterSpot[] = meters.map((m) => {
    const flip = Math.random() < 0.045;
    return {
      ...m,
      occupied: flip ? !m.occupied : m.occupied,
      lastSensorPingSecs: flip ? 1 : Math.min(59, m.lastSensorPingSecs + 4),
    };
  });

  // 4. Fluctuate Cross-Harbour Tunnel Crossing Times slightly
  const classifyTunnelStatus = (mins: number): 'good' | 'average' | 'bad' =>
    mins >= 15 ? 'bad' : mins >= 10 ? 'average' : 'good';

  const nextTunnels: TunnelCrossingMonitor[] = tunnels.map((t) => {
    const dHk = Math.random() > 0.65 ? (Math.random() > 0.5 ? 1 : -1) : 0;
    const dKln = Math.random() > 0.65 ? (Math.random() > 0.5 ? 1 : -1) : 0;
    const minFloor = t.id === 'whc' ? 4 : t.id === 'ehc' ? 7 : 12;
    const maxCeil = t.id === 'whc' ? 14 : t.id === 'ehc' ? 20 : 28;
    const toHkMins = Math.max(minFloor, Math.min(maxCeil, t.toHkMins + dHk));
    const toKlnMins = Math.max(minFloor, Math.min(maxCeil, t.toKlnMins + dKln));
    return {
      ...t,
      toHkMins,
      toKlnMins,
      toHkStatus: classifyTunnelStatus(toHkMins),
      toKlnStatus: classifyTunnelStatus(toKlnMins),
    };
  });

  return {
    carparks: nextCarparks,
    meters: nextMeters,
    roads: nextRoads,
    tunnels: nextTunnels,
  };
}

// Localization Helper Functions (繁 / 簡 / EN)
